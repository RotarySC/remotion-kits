/**
 * 展品的**中文名** —— 只服务展示页（`showcase/`），**不是运行时契约**。
 *
 * ## 为什么单开一个文件，而不是给 `ComponentSpec` / `LayoutSpec` / `Theme` 各加一个字段
 *
 * 1. **中文名是展示，不是运行。** `Theme` 与 `LAYOUT_SPECS` 在出片路径上被真正消费，
 *    往里塞只给展示页看的字段，等于让「运行契约」带上展示的尾巴。
 * 2. **不是每层都有声明文件**：家具只有 `FurnitureConfig` 的字段 + 文件，
 *    主题只有 `Theme` 对象，场景只有演示合成里 `<Sequence name>` 的字符串。
 *    逐层加字段会变成几套不同的机制；一张表 = 一套机制，管剩下的层。
 * 3. 于是**覆盖率可以被校验**（见下），这是它值得存在的前提。
 *
 * ## 为什么必须有覆盖率校验（`generate.ps1` 做）
 *
 * 缺中文名这件事**自己是不会响的** —— 页面照常渲染，只是那一格退回只有代码名，
 * 看起来像「本来就这样」。所以生成器会拿**发现到的**展品清单去比这张表：
 * 少一个 → `WARN`（这一格没有中文名）；多一个 → `WARN`（键打错了，或展品已经删了）。
 * 没有校验的声明一定会漂移，而漂移的展示页比没有更坏：它说谎。
 *
 * ## ⚠️ 本套件**只有四张子表** —— 这是拆分后的正常形态，不是漏写
 *
 * 内核与类型包拆开后，**原语与组件层场景归内核**（`kits/kernel/labels.ts`）：
 * 本套件不新增任何原语、也没有自己的 `KitShowcase`，所以没有 `elements` / `scenes` 两表。
 * 展示页上「元素墙」因此是内核那一页的事；本套件这一页只看它自己带来的东西。
 * （「一个类型包能做出什么」需要一个**合并视图** —— 那是资产声明要解决的问题，
 * 不是在这里补一张空表能糊过去的。）
 *
 * ## 格式约定
 *
 * 每层一个子表，键是**展品的代码名**（版式 = kebab 名、家具 = 文件基名、主题 = 主题 id），
 * 值是**短中文名**。短名不是说明 —— 每个版式还有 `LAYOUT_SPECS.purpose` 负责那一句话。
 * 这里只回答「**它叫什么**」。
 *
 * ⚠️ 值里不要出现单引号（生成器按 `'键': '值'` 逐行解析）。
 */

